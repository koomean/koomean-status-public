  function systemLanguage(languages) {
    const preferences = Array.isArray(languages) ? languages : [languages];
    for (const preference of preferences) {
      if (typeof preference !== "string") continue;
      const [preferred] = preference.trim().toLowerCase().split(/[-_]/, 1);
      if (preferred === "th" || preferred === "en") return preferred;
    }
    return "en";
  }

  function locale(language) {
    return language === "th" ? "th-TH-u-ca-gregory" : "en-GB";
  }

  function strings(language) {
    return language === "th" ? th : en;
  }

  function text(language, key, variables = {}) {
    return (strings(language)[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (placeholder, name) => (
      Object.hasOwn(variables, name) ? String(variables[name]) : placeholder
    ));
  }

  function plural(language, stem, count, variables = {}) {
    const category = count === 1 ? "one" : "other";
    return text(language, `${stem}.${category}`, { ...variables, count });
  }

  return Object.freeze({ systemLanguage, locale, strings, text, plural });
